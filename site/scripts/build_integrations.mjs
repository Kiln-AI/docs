/**
 * Two small `astro:build:done` checks, wired up in `astro.config.mjs`.
 *
 * Both exist because the thing they guard is invisible when it breaks: the
 * build stays green, nothing warns, and the damage only shows up in what
 * Cloudflare serves or in how big `dist` is.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Astro's static build discards the `Content-Type` an endpoint sets:
 * `core/build/generate.js` keeps `responseHeaders` only when an adapter
 * declares `staticHeaders`, and there is no adapter here — only the body is
 * written to disk. So the header the `.md` route returns never reaches
 * Cloudflare Pages, which is left to infer a type from the extension.
 *
 * This writes a Cloudflare Pages `_headers` file that says it explicitly.
 *
 * Every path is listed rather than matched with a `/*.md` pattern. Both work:
 * Cloudflare's `_headers` uses the same matching as `_redirects`, allows one
 * splat, and documents `/*.jpg` as an example, so a splat before a literal
 * suffix is supported. Enumeration is preferred because it is generated from
 * the files that were actually emitted, which proves the rules match reality
 * rather than asserting a pattern. The trade is that it spends one rule per
 * page against Cloudflare's cap of 100 — see MAX_HEADER_RULES.
 *
 * `public/_headers` wins if a human ever adds one, but silently losing all the
 * markdown rules is the failure this module exists to prevent, so that case
 * stops the build with merge instructions instead.
 */
export function markdownContentType() {
	return {
		name: 'kiln:markdown-content-type',
		hooks: {
			'astro:build:done': async ({ dir, logger }) => {
				const distDir = fileURLToPath(dir);
				const existing = await readFile(path.join(distDir, '_headers'), 'utf8').catch(
					() => null,
				);
				if (existing !== null && !existing.startsWith(GENERATED_HEADER)) {
					throw new Error(
						'dist/_headers was not generated by scripts/build_integrations.mjs, so it came ' +
							'from public/_headers. Overwriting it would drop your rules; leaving it would ' +
							'drop the Content-Type rules for every .md endpoint. Merge them: add\n\n' +
							`  ${MARKDOWN_GLOB_RULE.replace('\n', '\n  ')}\n\n` +
							'to public/_headers, then remove markdownContentType() from astro.config.mjs.',
					);
				}

				const paths = (await markdownEndpoints(distDir)).sort();
				if (paths.length > MAX_HEADER_RULES) {
					throw new Error(
						`${paths.length} .md endpoints would need ${paths.length} of Cloudflare's 100 ` +
							'`_headers` rules. Past the cap Cloudflare drops the overflow with no error, ' +
							'so switch this integration to the documented glob instead:\n\n' +
							`  ${MARKDOWN_GLOB_RULE.replace('\n', '\n  ')}`,
					);
				}

				const lines = [GENERATED_HEADER, ''];
				for (const urlPath of paths) {
					lines.push(urlPath, `  ${MARKDOWN_CONTENT_TYPE}`, '');
				}
				await writeFile(path.join(distDir, '_headers'), lines.join('\n'));
				logger.info(
					`wrote dist/_headers for ${paths.length} .md endpoints ` +
						`(${MAX_HEADER_RULES - paths.length} rules of headroom)`,
				);
			},
		},
	};
}

const GENERATED_HEADER =
	'# Generated by scripts/build_integrations.mjs - do not edit, do not commit.';

const MARKDOWN_CONTENT_TYPE = 'Content-Type: text/markdown; charset=utf-8';

/** The one-rule alternative to enumerating, if the count ever nears the cap. */
const MARKDOWN_GLOB_RULE = `/*.md\n${MARKDOWN_CONTENT_TYPE}`;

/**
 * Cloudflare Pages applies at most 100 `_headers` rules and drops the rest
 * silently. One rule per page means the corpus is the budget, so stop well
 * short and say what to do about it rather than shipping a truncated file.
 */
export const MAX_HEADER_RULES = 90;

async function markdownEndpoints(distDir) {
	const found = [];
	const walk = async (directory, prefix) => {
		for (const entry of await readdir(directory, { withFileTypes: true })) {
			if (entry.name.startsWith('_') || entry.name === 'pagefind') continue;
			if (entry.isDirectory()) {
				await walk(path.join(directory, entry.name), `${prefix}${entry.name}/`);
			} else if (entry.name.endsWith('.md')) {
				found.push(`${prefix}${entry.name}`);
			}
		}
	};
	await walk(distDir, '/');
	return found;
}

/**
 * `src/lib/page-markdown.ts` reads image metadata through the proxy's `clone`
 * escape hatch so that asking the image service for a URL does not also pin the
 * unoptimized original in the output. That trick is undocumented, and if Astro
 * ever drops it the fallback path silently reads the proxy again: build still
 * green, no warning, `dist/_astro` quietly ~7 MB heavier.
 *
 * So assert the symptom directly. Every image on the site is converted, so a
 * healthy build leaves at most a couple of originals behind; 68 of them means
 * the escape hatch is gone.
 */
export function optimizedImagesOnly({ maxOriginals = MAX_UNOPTIMIZED_ORIGINALS } = {}) {
	return {
		name: 'kiln:optimized-images-only',
		hooks: {
			'astro:build:done': async ({ dir }) => {
				const assetsDir = path.join(fileURLToPath(dir), '_astro');
				// An empty directory is a real answer; a missing one means this is
				// looking in the wrong place — `build.assets` renamed, or Astro's
				// default moved — and a gate that cannot find its subject must not
				// report a pass. That is the same silent failure it guards against.
				const names = await readdir(assetsDir).catch((cause) => {
					throw new Error(
						`cannot read ${assetsDir}, so the unoptimized-image check did not run. ` +
							'If Astro moved its asset directory, update this integration.',
						{ cause },
					);
				});
				const originals = names.filter((name) => ORIGINAL_IMAGE.test(name));
				if (originals.length > maxOriginals) {
					throw new Error(
						`dist/_astro holds ${originals.length} unoptimized images, expected at most ` +
							`${maxOriginals}. Astro is pinning originals it should have deleted — see ` +
							'plainMetadata() in src/lib/page-markdown.ts. Examples: ' +
							originals.slice(0, 3).join(', '),
					);
				}
			},
		},
	};
}

/**
 * One original survives today: `hero.png`, kept by the landing page's splash
 * hero. The allowance is deliberately tight — a regression pins all 68.
 */
export const MAX_UNOPTIMIZED_ORIGINALS = 4;

const ORIGINAL_IMAGE = /\.(png|jpe?g|gif|avif|tiff?)$/i;
